/**
 * Writes the site header into every public page between the header markers, so it's in the HTML
 * and paints on first frame instead of after the JS loads. Also writes each page's title,
 * description and share tags (from shared/seo.js) between the meta markers.
 * Run after changing lib/header.js or shared/seo.js:
 *   node scripts/bake-header.mjs
 */
import { readFile, writeFile } from 'node:fs/promises';
import { headerHTML } from '../assets/js/lib/header.js';
import { pageMetaTags } from '../assets/js/shared/seo.js';

// Page file -> the path it's served at (juice.html serves every /juices/<slug>)
const PAGES = {
	'index.html': '/',
	'juices.html': '/juices',
	'juice.html': '/juices/juice',
	'about.html': '/about',
	'contact.html': '/contact',
	'order.html': '/order',
	'success.html': '/success',
	'404.html': '/404'
};

const START = '<!-- header:start (generated by scripts/bake-header.mjs) -->';
const END = '<!-- header:end -->';
const META_START = '<!-- meta:start (generated by scripts/bake-header.mjs) -->';
const META_END = '<!-- meta:end -->';
const root = new URL('../', import.meta.url);
const between = (start, end) => new RegExp(`${start.replace(/[()]/g, '\\$&')}[\\s\\S]*?${end}`);

for (const [file, path] of Object.entries(PAGES)) {
	const url = new URL(file, root);
	const html = await readFile(url, 'utf8');
	const block = `${START}\n${headerHTML(path).replace(/^/gm, '    ')}\n    ${END}`;
	const meta = `${META_START}\n${pageMetaTags(path).replace(/^/gm, '    ')}\n    ${META_END}`;
	const next = (
		html.includes(START) ? html.replace(between(START, END), block.trimStart()) : html.replace(/(<body[^>]*>\n)/, `$1    ${block.trimStart()}\n`)
	).replace(between(META_START, META_END), () => meta.trimStart());
	if (next === html) continue;
	await writeFile(url, next);
	console.log(`baked ${file}`);
}
